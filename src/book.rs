#[cfg(test)]
mod tests {
    use super::*;
    use crate::project::{Kind, Project, ROOT};

    fn scratch(tag: &str) -> Project {
        let dir = std::env::temp_dir().join(format!("jqln-book-{}-{}", std::process::id(), tag));
        let _ = std::fs::remove_dir_all(&dir);
        let mut p = Project::create(&dir, "The Salt Road").unwrap();
        let roots: Vec<String> = p.children[ROOT].clone();
        for r in roots {
            p.remove(&r);
        }
        p
    }

    #[test]
    fn build_produces_a_title_page_and_numbered_chapters() {
        let mut p = scratch("build");
        p.book.author = "A. Writer".into();
        let ms = p.insert(ROOT, None, "Manuscript", Kind::Folder);
        let c1 = p.insert(&ms, None, "Chapter One", Kind::Folder);
        let s1 = p.insert(&c1, None, "Opening", Kind::Text);
        p.set_body(&s1, "The road ran west.".into());
        let c2 = p.insert(&ms, None, "Chapter Two", Kind::Folder);
        let s2 = p.insert(&c2, None, "Next", Kind::Text);
        p.set_body(&s2, "Rain by nightfall.".into());

        let doc = build(&mut p);
        assert!(doc.contains("#set document(title: \"The Salt Road\", author: \"A. Writer\")"));
        assert!(doc.contains("Copyright ©"));
        assert!(doc.contains("== Chapter One\n"));
        assert!(doc.contains("== Chapter Two\n"));
        assert!(doc.contains("#set page(numbering: \"1\""));
        assert!(doc.contains(r#"#"The road ran west.""#));
        let _ = std::fs::remove_dir_all(&p.root);
    }

    #[test]
    fn authored_front_matter_wins_over_generated() {
        let mut p = scratch("frontmatter");
        let fm = p.insert(ROOT, None, "Front Matter", Kind::Folder);
        let ded = p.insert(&fm, None, "Dedication", Kind::Text);
        p.set_body(&ded, "For the road.".into());
        let ms = p.insert(ROOT, None, "Manuscript", Kind::Folder);
        let c = p.insert(&ms, None, "One", Kind::Folder);
        p.insert(&c, None, "s", Kind::Text);

        let pages = front_matter(&mut p);
        // Generated title + generated copyright + the authored dedication.
        assert_eq!(pages.len(), 3);
        assert!(pages[2].contains("For the road."));
        let _ = std::fs::remove_dir_all(&p.root);
    }

    fn typst_available() -> bool {
        Command::new("typst").arg("--version").output().map(|o| o.status.success()).unwrap_or(false)
    }

    #[test]
    fn the_generated_document_compiles_with_typst() {
        if !typst_available() {
            eprintln!("skipping: typst not on PATH");
            return;
        }
        let mut p = scratch("compiles");
        p.book.author = "A. Writer".into();
        p.book.subtitle = "a novel".into();
        p.book.dedication = "For everyone who waited.".into();

        let fm = p.insert(ROOT, None, "Front Matter", Kind::Folder);
        let ack = p.insert(&fm, None, "Acknowledgements", Kind::Text);
        p.set_body(&ack, "Thanks to the usual suspects, and to *you*.".into());

        let ms = p.insert(ROOT, None, "Manuscript", Kind::Folder);
        let part = p.insert(&ms, None, "Part One", Kind::Folder);
        let c1 = p.insert(&part, None, "The Salt Flats", Kind::Folder);
        let s1 = p.insert(&c1, None, "Opening", Kind::Text);
        p.set_body(
            &s1,
            "The road out of the flats was **white** and it went on for a *very* long way.\n\n\
             He counted the miles the way you count anything that will not end.\n\n* * *\n\n\
             By nightfall there was rain — the kind that arrives sideways.\n\n\\newpage\n\n\
             ::: center\nAnd then, nothing.\n:::".into(),
        );
        let c2 = p.insert(&part, None, "Chapter 2", Kind::Folder);
        let s2 = p.insert(&c2, None, "Next", Kind::Text);
        p.set_body(&s2, "She had a #hashtag problem and a [bracket] habit. Both survived.".into());

        let outcome = compile_to_file(&mut p).unwrap();
        match outcome {
            Outcome::Pdf { pdf, .. } => assert!(pdf.exists(), "no pdf produced"),
            Outcome::TypstFailed { message, typ } => {
                let src = std::fs::read_to_string(&typ).unwrap();
                panic!("typst rejected the document: {message}\n---\n{src}");
            }
            Outcome::TypstMissing { .. } => unreachable!("typst was reported available"),
        }
        let _ = std::fs::remove_dir_all(&p.root);
    }

    #[test]
    fn compile_writes_a_typ_file_even_without_typst() {
        let mut p = scratch("typ");
        let ms = p.insert(ROOT, None, "Manuscript", Kind::Folder);
        let c = p.insert(&ms, None, "One", Kind::Folder);
        let s = p.insert(&c, None, "s", Kind::Text);
        p.set_body(&s, "Words.".into());

        let outcome = compile_to_file(&mut p).unwrap();
        let typ = match outcome {
            Outcome::Pdf { typ, .. } | Outcome::TypstMissing { typ } | Outcome::TypstFailed { typ, .. } => typ,
        };
        assert!(typ.exists());
        assert!(typ.ends_with("the-salt-road.typ"));
        assert!(std::fs::read_to_string(&typ).unwrap().contains("== Chapter One"));
        let _ = std::fs::remove_dir_all(&p.root);
    }
}

